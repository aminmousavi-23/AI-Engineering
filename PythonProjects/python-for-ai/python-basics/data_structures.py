# ============================================================
# 1. Lists
# ============================================================


# ------------------------------------------------------------
# 1.1 Creating Lists
# ------------------------------------------------------------

# Empty list
my_list = []

# List with items
fruits = ["apple", "banana", "orange"]
numbers = [1, 2, 3, 4, 5]
mixed = ["hello", 42, True, 3.14]  # Different types are OK


# ------------------------------------------------------------
# 1.2 Accessing Items
# ------------------------------------------------------------

fruits = ["apple", "banana", "orange"]

print(fruits[0])     # "apple"
print(fruits[1])     # "banana"
print(fruits[-1])    # "orange"
print(fruits[-2])    # "banana"


# ------------------------------------------------------------
# 1.3 Slicing
# ------------------------------------------------------------

print(fruits[0:2])   # ["apple", "banana"]
print(fruits[1:])    # ["banana", "orange"]


# ------------------------------------------------------------
# 1.4 Changing Items
# ------------------------------------------------------------

fruits[0] = "mango"

print(fruits)


# ------------------------------------------------------------
# 1.5 Adding Items
# ------------------------------------------------------------

fruits.append("grape")
fruits.insert(1, "kiwi")


# ------------------------------------------------------------
# 1.6 Removing Items
# ------------------------------------------------------------

fruits.remove("banana")

last = fruits.pop()

del fruits[0]


# ------------------------------------------------------------
# 1.7 Information
# ------------------------------------------------------------

numbers = [3, 1, 4, 1, 5, 9]

print(len(numbers))         # 6
print(numbers.count(1))     # 2
print(numbers.index(4))     # 2


# ------------------------------------------------------------
# 1.8 Sorting
# ------------------------------------------------------------

numbers.sort()

print(numbers)              # [1, 1, 3, 4, 5, 9]

numbers.reverse()

print(numbers)              # [9, 5, 4, 3, 1, 1]


# ------------------------------------------------------------
# 1.9 Copying
# ------------------------------------------------------------

new_list = numbers.copy()


# ------------------------------------------------------------
# 1.10 Checking Items
# ------------------------------------------------------------

fruits = ["apple", "banana", "orange"]

if "apple" in fruits:
    print("Found apple!")


# ------------------------------------------------------------
# 1.11 Checking if Empty
# ------------------------------------------------------------

if fruits:
    print("List has items")
else:
    print("List is empty")


# ------------------------------------------------------------
# 1.12 Modifying During a Loop
# ------------------------------------------------------------

# Dangerous - don't modify a list while iterating over it

numbers = [1, 2, 3, 4]

for num in numbers:
    if num == 2:
        numbers.remove(num)


# Better - use list comprehension

numbers = [num for num in numbers if num != 2]


# ------------------------------------------------------------
# 1.13 References vs Copies
# ------------------------------------------------------------

# Wrong - both variables point to the same list

list1 = [1, 2, 3]
list2 = list1

list2.append(4)

print(list1)               # [1, 2, 3, 4]


# Right - make a copy

list1 = [1, 2, 3]
list2 = list1.copy()

list2.append(4)

print(list1)               # [1, 2, 3]


# ============================================================
# 2. Dictionaries
# ============================================================


# ------------------------------------------------------------
# 2.1 Creating a Dictionary
# ------------------------------------------------------------

person = {
    "name": "Alice",
    "age": 18,
    "city": "New York"
}


# ------------------------------------------------------------
# 2.2 Changing and Adding Items
# ------------------------------------------------------------

person["name"] = "Dave"
person["license"] = True

print(person)


# ------------------------------------------------------------
# 2.3 Deleting Items
# ------------------------------------------------------------

del person["license"]

print(person)


# ------------------------------------------------------------
# 2.4 Getting Values
# ------------------------------------------------------------

print(person.get("job"))
print(person.get("job", "Unknown"))


# ------------------------------------------------------------
# 2.5 Removing Items
# ------------------------------------------------------------

age = person.pop("age")

person.clear()


# ------------------------------------------------------------
# 2.6 Getting Keys, Values, and Items
# ------------------------------------------------------------

person = {
    "name": "Alice",
    "age": 30,
    "city": "New York"
}

print(person.keys())
print(person.values())
print(person.items())


# ------------------------------------------------------------
# 2.7 Checking if a Key Exists
# ------------------------------------------------------------

if "name" in person:
    print("Name found!")


# ------------------------------------------------------------
# 2.8 Updating Multiple Values
# ------------------------------------------------------------

person.update({
    "age": 31,
    "job": "Engineer"
})


# ------------------------------------------------------------
# 2.9 Nested Dictionaries
# ------------------------------------------------------------

students = {
    "alice": {
        "age": 20,
        "grade": "A"
    },
    "bob": {
        "age": 21,
        "grade": "B"
    },
    "charlie": {
        "age": 19,
        "grade": "A"
    }
}

print(students["alice"]["grade"])


# ------------------------------------------------------------
# 2.10 Avoiding KeyError
# ------------------------------------------------------------

person = {"name": "Alice"}

# Wrong - raises KeyError if "age" doesn't exist
# print(person["age"])

# Right - use get()
print(person.get("age", 0))


# ============================================================
# 3. Tuples
# ============================================================


# ------------------------------------------------------------
# 3.1 Creating Tuples
# ------------------------------------------------------------

empty = ()

point = (3, 5)

colors = ("red", "green", "blue")


# ------------------------------------------------------------
# 3.2 Single-Item Tuple
# ------------------------------------------------------------

# A single-item tuple needs a comma

single = (42,)

# This is NOT a tuple
not_tuple = (42)


# ------------------------------------------------------------
# 3.3 Implicit Tuples
# ------------------------------------------------------------

coordinates = 10, 20


# ------------------------------------------------------------
# 3.4 Accessing Items
# ------------------------------------------------------------

point = (3, 5)
colors = ("red", "green", "blue")

print(point[0])
print(colors[-1])


# ------------------------------------------------------------
# 3.5 Tuple Slicing
# ------------------------------------------------------------

print(colors[0:2])


# ------------------------------------------------------------
# 3.6 Tuple Unpacking
# ------------------------------------------------------------

point = (3, 5)

x, y = point

print(x)
print(y)


# ------------------------------------------------------------
# 3.7 Multiple Assignment
# ------------------------------------------------------------

a, b, c = 1, 2, 3


# ------------------------------------------------------------
# 3.8 Swapping Variables
# ------------------------------------------------------------

x, y = y, x


# ------------------------------------------------------------
# 3.9 Checking Tuple Type
# ------------------------------------------------------------

# Wrong - this is an int

single = (42)

print(type(single))


# Right - include the comma

single = (42,)

print(type(single))


# ------------------------------------------------------------
# 3.10 Tuples Are Immutable
# ------------------------------------------------------------

point = (3, 5)

# This causes TypeError
# point[0] = 4


# ------------------------------------------------------------
# 3.11 Creating a New Tuple
# ------------------------------------------------------------

point = (4, point[1])

print(point)


# ------------------------------------------------------------
# 3.12 Convert Tuple -> List -> Tuple
# ------------------------------------------------------------

point = (3, 5)

temp = list(point)

temp[0] = 4

point = tuple(temp)

print(point)


# ============================================================
# 4. Sets
# ============================================================


# ------------------------------------------------------------
# 4.1 Creating Sets
# ------------------------------------------------------------

# Empty set
empty_set = set()

# Empty {} creates a dictionary, NOT a set
empty_dict = {}

# Set with values
numbers = {1, 2, 3, 4, 5}

fruits = set(["apple", "banana", "orange"])


# ------------------------------------------------------------
# 4.2 Creating a Set from a List
# ------------------------------------------------------------

# Duplicate values are removed

scores = [85, 90, 85, 92, 90]

unique_scores = set(scores)

print(unique_scores)        # {85, 90, 92}


# ------------------------------------------------------------
# 4.3 Adding Items
# ------------------------------------------------------------

colors = {"red", "blue"}

colors.add("green")

print(colors)


# ------------------------------------------------------------
# 4.4 Removing Items
# ------------------------------------------------------------

# remove() raises an error if the item doesn't exist
colors.remove("blue")

# discard() does not raise an error if the item doesn't exist
colors.discard("yellow")


# ------------------------------------------------------------
# 4.5 Checking Membership
# ------------------------------------------------------------

if "red" in colors:
    print("Red is available")


# ------------------------------------------------------------
# 4.6 Removing Duplicates
# ------------------------------------------------------------

names = [
    "Alice",
    "Bob",
    "Alice",
    "Charlie",
    "Bob"
]

unique_names = list(set(names))

print(unique_names)


# ------------------------------------------------------------
# 4.7 Set Membership
# ------------------------------------------------------------

allowed_users = {
    "alice",
    "bob",
    "charlie"
}

if "alice" in allowed_users:
    print("Access granted")


# ------------------------------------------------------------
# 4.8 Set vs Dictionary
# ------------------------------------------------------------

# Wrong - creates an empty dictionary
empty = {}

# Right - creates an empty set
empty = set()


# ------------------------------------------------------------
# 4.9 Set Order
# ------------------------------------------------------------

# Sets are unordered collections.
# Do not rely on a particular iteration/display order.

numbers = {3, 1, 4, 1, 5}

print(numbers)


# Use a list when order matters

ordered = [3, 1, 4, 1, 5]

print(ordered)