# ============================================================
# Control Flow
# ============================================================


# ------------------------------------------------------------
# 1. If Statements
# ------------------------------------------------------------

temperature = 5

if temperature > 25:
    print("It's hot!")
elif temperature < 15:
    print("It's cold")
else:
    print("It's nice weather!")


# ------------------------------------------------------------
# 2. If Statements - Multiple Conditions
# ------------------------------------------------------------

age = 25
has_license = True

if age >= 18 and has_license:
    print("You can drive!")


# ------------------------------------------------------------
# 3. If Statements - Comparison Operators
# ------------------------------------------------------------

x = 10

if x == 10:
    print("x is 10")

if x != 5:
    print("x is not 5")

if x > 5:
    print("x is greater than 5")

if x < 20:
    print("x is less than 20")


# ------------------------------------------------------------
# 4. If Statements - Logical Operators
# ------------------------------------------------------------

age = 25
has_license = True
has_car = True

if age >= 18 and has_license:
    print("Can drive")

if age < 18 or not has_license:
    print("Cannot drive")

if has_license and has_car:
    print("Can drive your own car")


# ============================================================
# Loops
# ============================================================


# ------------------------------------------------------------
# 5. For Loop - range()
# ------------------------------------------------------------

for i in range(5):
    print(i)


# ------------------------------------------------------------
# 6. For Loop - Start and End
# ------------------------------------------------------------

for i in range(1, 6):
    print(i)


# ------------------------------------------------------------
# 7. For Loop - Start, End, Step
# ------------------------------------------------------------

for i in range(0, 10, 2):
    print(i)


# ------------------------------------------------------------
# 8. For Loop - Strings
# ------------------------------------------------------------

name = "Python"

for letter in name:
    print(letter)


# ------------------------------------------------------------
# 9. For Loop - Lists
# ------------------------------------------------------------

colors = ["red", "blue", "green"]

for color in colors:
    print(f"I like {color}")


# ------------------------------------------------------------
# 10. While Loop
# ------------------------------------------------------------

count = 0

while count < 5:
    print(f"Count is {count}")
    count = count + 1


# ------------------------------------------------------------
# 11. Loop Control - break
# ------------------------------------------------------------

for i in range(10):
    if i == 5:
        break

    print(i)


# ------------------------------------------------------------
# 12. Loop Control - continue
# ------------------------------------------------------------

for i in range(5):
    if i == 2:
        continue

    print(i)